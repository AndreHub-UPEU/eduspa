-- Responsabilidad: estructura académica del colegio (año, periodos,
-- niveles, grados, secciones, aulas, cursos, malla, docentes, asignación
-- docente-curso-sección y horario).
-- Regla Database-per-Service: ninguna FK sale de esta base.
-- Los ids de otros servicios (usuario_id de auth-ms) se guardan como
-- columna simple, sin FOREIGN KEY.
-- =====================================================================

-- ---------- Año académico ----------
CREATE TABLE anios_academicos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(20)  NOT NULL,                 -- '2026'
    fecha_inicio  DATE         NOT NULL,
    fecha_fin     DATE         NOT NULL,
    estado        VARCHAR(15)  NOT NULL DEFAULT 'PLANIFICADO',
    creado_en     TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_anio_nombre UNIQUE (nombre),
    CONSTRAINT ck_anio_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_anio_estado CHECK (estado IN ('PLANIFICADO','ACTIVO','CERRADO'))
);
-- Solo un año ACTIVO a la vez
CREATE UNIQUE INDEX uk_anio_unico_activo ON anios_academicos (estado) WHERE estado = 'ACTIVO';

-- ---------- Periodos (bimestres / trimestres) ----------
CREATE TABLE periodos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_academico_id BIGINT      NOT NULL REFERENCES anios_academicos(id),
    numero           SMALLINT     NOT NULL,
    nombre           VARCHAR(40)  NOT NULL,               -- 'I Bimestre'
    fecha_inicio     DATE         NOT NULL,
    fecha_fin        DATE         NOT NULL,
    estado           VARCHAR(15)  NOT NULL DEFAULT 'PLANIFICADO',
    CONSTRAINT uk_periodo_anio_numero UNIQUE (anio_academico_id, numero),
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_periodo_estado CHECK (estado IN ('PLANIFICADO','ACTIVO','CERRADO'))
);
CREATE INDEX idx_periodos_anio ON periodos (anio_academico_id);

-- ---------- Niveles (Inicial, Primaria, Secundaria) ----------
CREATE TABLE niveles (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(15) NOT NULL,
    nombre  VARCHAR(50) NOT NULL,
    orden   SMALLINT    NOT NULL,
    activo  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_nivel_codigo UNIQUE (codigo)
);

-- ---------- Grados (1° Primaria, 2° Primaria...) ----------
CREATE TABLE grados (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel_id  BIGINT      NOT NULL REFERENCES niveles(id),
    numero    SMALLINT    NOT NULL,
    nombre    VARCHAR(50) NOT NULL,
    activo    BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_grado_nivel_numero UNIQUE (nivel_id, numero)
);

-- ---------- Aulas físicas ----------
CREATE TABLE aulas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(20) NOT NULL,
    nombre     VARCHAR(80) NOT NULL,
    tipo       VARCHAR(20) NOT NULL DEFAULT 'AULA',
    capacidad  SMALLINT    NOT NULL,
    activo     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_aula_codigo UNIQUE (codigo),
    CONSTRAINT ck_aula_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_aula_tipo CHECK (tipo IN ('AULA','LABORATORIO','COMPUTO','AUDITORIO','PATIO','OTRO'))
);

-- ---------- Secciones (1° A, 1° B por año) ----------
CREATE TABLE secciones (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_academico_id BIGINT      NOT NULL REFERENCES anios_academicos(id),
    grado_id          BIGINT      NOT NULL REFERENCES grados(id),
    aula_id           BIGINT      REFERENCES aulas(id),
    nombre            VARCHAR(10) NOT NULL,               -- 'A'
    turno             VARCHAR(10) NOT NULL DEFAULT 'MANANA',
    capacidad         SMALLINT    NOT NULL DEFAULT 30,
    tutor_docente_id  BIGINT,                             -- FK lógica a docentes (se agrega abajo)
    activo            BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_seccion UNIQUE (anio_academico_id, grado_id, nombre),
    CONSTRAINT ck_seccion_turno CHECK (turno IN ('MANANA','TARDE')),
    CONSTRAINT ck_seccion_capacidad CHECK (capacidad > 0)
);
CREATE INDEX idx_secciones_anio_grado ON secciones (anio_academico_id, grado_id);

-- ---------- Cursos / Áreas ----------
CREATE TABLE cursos (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(20)  NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    area    VARCHAR(60),
    activo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_curso_codigo UNIQUE (codigo)
);

-- ---------- Malla curricular: qué cursos lleva cada grado ----------
CREATE TABLE grado_cursos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grado_id         BIGINT   NOT NULL REFERENCES grados(id),
    curso_id         BIGINT   NOT NULL REFERENCES cursos(id),
    horas_semanales  SMALLINT NOT NULL DEFAULT 2,
    CONSTRAINT uk_grado_curso UNIQUE (grado_id, curso_id),
    CONSTRAINT ck_horas CHECK (horas_semanales > 0)
);

-- ---------- Docentes ----------
CREATE TABLE docentes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT,                              -- id en auth-ms (sin FK)
    tipo_documento   VARCHAR(10)  NOT NULL DEFAULT 'DNI',
    numero_documento VARCHAR(20)  NOT NULL,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    email            VARCHAR(150),
    telefono         VARCHAR(20),
    especialidad     VARCHAR(100),
    estado           VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
    creado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_docente_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uk_docente_usuario UNIQUE (usuario_id),
    CONSTRAINT ck_docente_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);
CREATE INDEX idx_docentes_apellidos ON docentes (apellidos, nombres);

ALTER TABLE secciones
    ADD CONSTRAINT fk_seccion_tutor FOREIGN KEY (tutor_docente_id) REFERENCES docentes(id);

-- ---------- Asignación: docente dicta curso en sección ----------
CREATE TABLE asignaciones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id  BIGINT NOT NULL REFERENCES secciones(id),
    curso_id    BIGINT NOT NULL REFERENCES cursos(id),
    docente_id  BIGINT NOT NULL REFERENCES docentes(id),
    CONSTRAINT uk_asignacion UNIQUE (seccion_id, curso_id)
);
CREATE INDEX idx_asignaciones_docente ON asignaciones (docente_id);

-- ---------- Bloques horarios (franjas del día) ----------
CREATE TABLE bloques_horarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno       VARCHAR(10) NOT NULL,
    orden       SMALLINT    NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL,
    es_receso   BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_bloque UNIQUE (turno, orden),
    CONSTRAINT ck_bloque_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_bloque_turno CHECK (turno IN ('MANANA','TARDE'))
);

-- ---------- Horario: una clase = asignación + día + bloque (+ aula) ----------
CREATE TABLE horarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignacion_id  BIGINT   NOT NULL REFERENCES asignaciones(id) ON DELETE CASCADE,
    bloque_id      BIGINT   NOT NULL REFERENCES bloques_horarios(id),
    aula_id        BIGINT   REFERENCES aulas(id),
    dia_semana     SMALLINT NOT NULL,                     -- 1=lunes ... 7=domingo
    CONSTRAINT ck_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT uk_horario_asignacion_slot UNIQUE (asignacion_id, dia_semana, bloque_id)
);
CREATE INDEX idx_horarios_slot ON horarios (dia_semana, bloque_id);
CREATE INDEX idx_horarios_aula ON horarios (aula_id, dia_semana, bloque_id);

-- ---------- Publicaciones de horario (versión por sección) ----------
CREATE TABLE publicaciones_horario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id    BIGINT    NOT NULL REFERENCES secciones(id),
    version       INTEGER   NOT NULL,
    publicado_por BIGINT,                                 -- usuario_id en auth-ms (sin FK)
    publicado_en  TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_publicacion UNIQUE (seccion_id, version)
);

-- ---------- Feriados / días no laborables ----------
CREATE TABLE feriados (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_academico_id BIGINT       NOT NULL REFERENCES anios_academicos(id),
    fecha             DATE         NOT NULL,
    descripcion       VARCHAR(150) NOT NULL,
    CONSTRAINT uk_feriado UNIQUE (anio_academico_id, fecha)
);


-- =====================================================================
-- notificaciones_db  |  notificaciones-ms  |  EduSpace
-- Flyway: src/main/resources/db/migration/V1__init_notificaciones.sql
-- Responsabilidad: bandeja de notificaciones, plantillas, preferencias,
-- dispositivos push y trazabilidad de envíos. Se alimenta de eventos Kafka.
-- Ids externos (usuario_id de auth-ms) sin FOREIGN KEY.
-- =====================================================================

-- ---------- Plantillas por tipo de evento y canal ----------
CREATE TABLE plantillas_notificacion (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(60)  NOT NULL,                  -- p.ej. 'PAGO_CONFIRMADO'
    canal         VARCHAR(10)  NOT NULL,
    asunto        VARCHAR(200),
    cuerpo        TEXT         NOT NULL,                  -- con marcadores {{nombre}}, {{monto}}...
    activa        BOOLEAN      NOT NULL DEFAULT TRUE,
    actualizado_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_plantilla UNIQUE (codigo, canal),
    CONSTRAINT ck_plantilla_canal CHECK (canal IN ('IN_APP','EMAIL','PUSH'))
);

-- ---------- Notificaciones (bandeja) ----------
CREATE TABLE notificaciones (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT       NOT NULL,               -- destinatario (auth-ms)
    tipo             VARCHAR(60)  NOT NULL,               -- código de plantilla / evento
    canal            VARCHAR(10)  NOT NULL DEFAULT 'IN_APP',
    titulo           VARCHAR(200) NOT NULL,
    mensaje          TEXT         NOT NULL,
    datos_json       JSONB,                              -- payload útil para el deep-link del cliente
    evento_origen    VARCHAR(80),                         -- topic Kafka de origen
    evento_clave     VARCHAR(80),                         -- key del evento (id de la entidad)
    estado           VARCHAR(12)  NOT NULL DEFAULT 'PENDIENTE',
    leida            BOOLEAN      NOT NULL DEFAULT FALSE,
    leida_en         TIMESTAMP,
    creada_en        TIMESTAMP    NOT NULL DEFAULT now(),
    enviada_en       TIMESTAMP,
    CONSTRAINT ck_notif_canal CHECK (canal IN ('IN_APP','EMAIL','PUSH')),
    CONSTRAINT ck_notif_estado CHECK (estado IN ('PENDIENTE','ENVIADA','FALLIDA','DESCARTADA'))
);
CREATE INDEX idx_notif_usuario_fecha ON notificaciones (usuario_id, creada_en DESC);
CREATE INDEX idx_notif_no_leidas ON notificaciones (usuario_id) WHERE leida = FALSE;
CREATE INDEX idx_notif_pendientes ON notificaciones (estado) WHERE estado IN ('PENDIENTE','FALLIDA');

-- Anti-duplicado (Kafka es at-least-once): el mismo evento no genera dos veces
-- la misma notificación para el mismo usuario/tipo/canal.
CREATE UNIQUE INDEX uk_notif_evento ON notificaciones (usuario_id, tipo, canal, evento_origen, evento_clave)
    WHERE evento_clave IS NOT NULL;

-- ---------- Preferencias por usuario/tipo/canal ----------
CREATE TABLE preferencias_notificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL,
    tipo        VARCHAR(60) NOT NULL,
    canal       VARCHAR(10) NOT NULL,
    habilitada  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_preferencia UNIQUE (usuario_id, tipo, canal),
    CONSTRAINT ck_pref_canal CHECK (canal IN ('IN_APP','EMAIL','PUSH'))
);

-- ---------- Dispositivos para push (app Flutter) ----------
CREATE TABLE dispositivos_push (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       NOT NULL,
    token        VARCHAR(400) NOT NULL,
    plataforma   VARCHAR(10)  NOT NULL,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    registrado_en TIMESTAMP   NOT NULL DEFAULT now(),
    ultimo_uso   TIMESTAMP,
    CONSTRAINT uk_dispositivo_token UNIQUE (token),
    CONSTRAINT ck_disp_plataforma CHECK (plataforma IN ('ANDROID','IOS','WEB'))
);
CREATE INDEX idx_disp_usuario ON dispositivos_push (usuario_id) WHERE activo;

-- ---------- Intentos de envío (trazabilidad de EMAIL/PUSH) ----------
CREATE TABLE intentos_envio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notificacion_id  BIGINT      NOT NULL REFERENCES notificaciones(id) ON DELETE CASCADE,
    numero_intento   SMALLINT    NOT NULL,
    exitoso          BOOLEAN     NOT NULL,
    error            VARCHAR(500),
    intentado_en     TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_intento UNIQUE (notificacion_id, numero_intento)
);


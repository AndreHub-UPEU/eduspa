-- alumnos_db  |  alumnos-ms  |  EduSpace
-- Flyway: src/main/resources/db/migration/V1__init_alumnos.sql
-- Responsabilidad: expediente del alumno (datos personales, apoderados,
-- documentos, ficha de salud básica e historial de estado).
-- NO guarda grado ni sección: eso pertenece a matricula-ms.
-- Ids externos (usuario_id de auth-ms) sin FOREIGN KEY.
-- =====================================================================

CREATE TABLE alumnos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(20)  NOT NULL,             -- código interno, generado por el servicio
    usuario_id         BIGINT,                            -- id en auth-ms (si el alumno tiene cuenta)
    tipo_documento     VARCHAR(10)  NOT NULL DEFAULT 'DNI',
    numero_documento   VARCHAR(20)  NOT NULL,
    nombres            VARCHAR(100) NOT NULL,
    apellido_paterno   VARCHAR(80)  NOT NULL,
    apellido_materno   VARCHAR(80),
    fecha_nacimiento   DATE         NOT NULL,
    sexo               CHAR(1)      NOT NULL,
    nacionalidad       VARCHAR(50)  DEFAULT 'Peruana',
    direccion          VARCHAR(200),
    distrito           VARCHAR(80),
    telefono           VARCHAR(20),
    email              VARCHAR(150),
    foto_url           VARCHAR(300),
    colegio_procedencia VARCHAR(150),
    estado             VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
    creado_en          TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en     TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_alumno_codigo UNIQUE (codigo),
    CONSTRAINT uk_alumno_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uk_alumno_usuario UNIQUE (usuario_id),
    CONSTRAINT ck_alumno_sexo CHECK (sexo IN ('M','F')),
    CONSTRAINT ck_alumno_estado CHECK (estado IN ('ACTIVO','RETIRADO','EGRESADO','TRASLADADO','INACTIVO'))
);
CREATE INDEX idx_alumnos_apellidos ON alumnos (apellido_paterno, apellido_materno, nombres);
CREATE INDEX idx_alumnos_estado ON alumnos (estado);

-- ---------- Apoderados (padres / tutores legales) ----------
CREATE TABLE apoderados (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT,                              -- id en auth-ms (rol APODERADO)
    tipo_documento   VARCHAR(10)  NOT NULL DEFAULT 'DNI',
    numero_documento VARCHAR(20)  NOT NULL,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(150) NOT NULL,
    telefono         VARCHAR(20),
    telefono_alterno VARCHAR(20),
    email            VARCHAR(150),
    direccion        VARCHAR(200),
    ocupacion        VARCHAR(100),
    creado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_apoderado_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uk_apoderado_usuario UNIQUE (usuario_id)
);
CREATE INDEX idx_apoderados_apellidos ON apoderados (apellidos, nombres);

-- ---------- Relación alumno <-> apoderado ----------
CREATE TABLE alumno_apoderado (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id             BIGINT      NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    apoderado_id          BIGINT      NOT NULL REFERENCES apoderados(id),
    parentesco            VARCHAR(20) NOT NULL,
    es_principal          BOOLEAN     NOT NULL DEFAULT FALSE,
    es_responsable_pago   BOOLEAN     NOT NULL DEFAULT FALSE,
    vive_con_alumno       BOOLEAN     NOT NULL DEFAULT TRUE,
    puede_recoger         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_alumno_apoderado UNIQUE (alumno_id, apoderado_id),
    CONSTRAINT ck_parentesco CHECK (parentesco IN ('PADRE','MADRE','ABUELO','ABUELA','TIO','TIA','HERMANO','TUTOR','OTRO'))
);
CREATE INDEX idx_aa_apoderado ON alumno_apoderado (apoderado_id);
-- Un solo apoderado principal por alumno
CREATE UNIQUE INDEX uk_aa_un_principal ON alumno_apoderado (alumno_id) WHERE es_principal;
-- Un solo responsable de pago por alumno
CREATE UNIQUE INDEX uk_aa_un_resp_pago ON alumno_apoderado (alumno_id) WHERE es_responsable_pago;

-- ---------- Documentos del expediente ----------
CREATE TABLE alumno_documentos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id     BIGINT       NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    tipo          VARCHAR(30)  NOT NULL,
    nombre_archivo VARCHAR(200) NOT NULL,
    ruta_storage  VARCHAR(400) NOT NULL,                  -- clave en MinIO/S3
    content_type  VARCHAR(100),
    tamano_bytes  BIGINT,
    verificado    BOOLEAN      NOT NULL DEFAULT FALSE,
    subido_en     TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_doc_tipo CHECK (tipo IN ('PARTIDA_NACIMIENTO','DNI','CERTIFICADO_ESTUDIOS','FICHA_SIAGIE','CARNET_VACUNACION','FOTO','OTRO'))
);
CREATE INDEX idx_alumno_docs_alumno ON alumno_documentos (alumno_id);

-- ---------- Ficha de salud básica (uso escolar) ----------
CREATE TABLE alumno_salud (
    alumno_id           BIGINT PRIMARY KEY REFERENCES alumnos(id) ON DELETE CASCADE,
    grupo_sanguineo     VARCHAR(5),
    alergias            VARCHAR(300),
    observaciones       VARCHAR(500),
    seguro_medico       VARCHAR(100),
    contacto_emergencia_nombre   VARCHAR(150),
    contacto_emergencia_telefono VARCHAR(20),
    actualizado_en      TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------- Historial de cambios de estado ----------
CREATE TABLE alumno_estado_historial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id       BIGINT      NOT NULL REFERENCES alumnos(id) ON DELETE CASCADE,
    estado_anterior VARCHAR(15),
    estado_nuevo    VARCHAR(15) NOT NULL,
    motivo          VARCHAR(300),
    usuario_id      BIGINT,                               -- quién hizo el cambio (auth-ms)
    cambiado_en     TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_estado_hist_alumno ON alumno_estado_historial (alumno_id, cambiado_en DESC);

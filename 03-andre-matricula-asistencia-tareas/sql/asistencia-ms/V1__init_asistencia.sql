-- Registro diario (primaria: por día) o por curso/bloque (secundaria).
-- La lista de alumnos de una sección sale de matriculas_local (réplica
-- alimentada por eventos matricula.*), no de llamadas síncronas.
-- =====================================================================

-- Réplica local (read model) de matrículas, alimentada por eventos matricula.*
CREATE TABLE matriculas_local (
    matricula_id   BIGINT       PRIMARY KEY,
    alumno_id      BIGINT       NOT NULL,
    alumno_nombre  VARCHAR(220) NOT NULL,
    anio_id        BIGINT       NOT NULL,
    nivel_id       BIGINT,
    grado_id       BIGINT       NOT NULL,
    seccion_id     BIGINT       NOT NULL,
    estado         VARCHAR(15)  NOT NULL,
    actualizado_en TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ml_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
CREATE INDEX idx_ml_seccion ON matriculas_local (seccion_id, estado);
CREATE INDEX idx_ml_alumno ON matriculas_local (alumno_id);


CREATE TABLE sesiones_asistencia (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id       BIGINT      NOT NULL,
    periodo_id    BIGINT,
    seccion_id    BIGINT      NOT NULL,
    fecha         DATE        NOT NULL,
    tipo          VARCHAR(6)  NOT NULL DEFAULT 'DIA',
    curso_id      BIGINT,
    bloque_id     BIGINT,
    docente_id    BIGINT      NOT NULL,                    -- planificacion-ms
    estado        VARCHAR(8)  NOT NULL DEFAULT 'ABIERTA',
    abierta_por   BIGINT,
    creada_en     TIMESTAMP   NOT NULL DEFAULT now(),
    cerrada_en    TIMESTAMP,
    cerrada_por   BIGINT,
    CONSTRAINT ck_ses_tipo CHECK (tipo IN ('DIA','CURSO')),
    CONSTRAINT ck_ses_estado CHECK (estado IN ('ABIERTA','CERRADA')),
    CONSTRAINT ck_ses_coherencia CHECK (
        (tipo = 'DIA'   AND curso_id IS NULL AND bloque_id IS NULL) OR
        (tipo = 'CURSO' AND curso_id IS NOT NULL AND bloque_id IS NOT NULL))
);
CREATE UNIQUE INDEX uk_ses_dia ON sesiones_asistencia (seccion_id, fecha) WHERE tipo = 'DIA';
CREATE UNIQUE INDEX uk_ses_curso ON sesiones_asistencia (seccion_id, fecha, curso_id, bloque_id) WHERE tipo = 'CURSO';
CREATE INDEX idx_ses_fecha ON sesiones_asistencia (fecha);
CREATE INDEX idx_ses_docente ON sesiones_asistencia (docente_id, fecha);

CREATE TABLE asistencia_detalle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id      BIGINT      NOT NULL REFERENCES sesiones_asistencia(id) ON DELETE CASCADE,
    matricula_id   BIGINT      NOT NULL,
    alumno_id      BIGINT      NOT NULL,
    estado         VARCHAR(11) NOT NULL,
    minutos_tarde  SMALLINT,
    observacion    VARCHAR(300),
    registrado_en  TIMESTAMP   NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_det_sesion_matricula UNIQUE (sesion_id, matricula_id),
    CONSTRAINT ck_det_estado CHECK (estado IN ('PRESENTE','FALTA','TARDANZA','JUSTIFICADO')),
    CONSTRAINT ck_det_minutos CHECK (minutos_tarde IS NULL OR minutos_tarde > 0)
);
CREATE INDEX idx_det_alumno ON asistencia_detalle (alumno_id, estado);
CREATE INDEX idx_det_matricula ON asistencia_detalle (matricula_id);

CREATE TABLE justificaciones (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id       BIGINT       NOT NULL,
    alumno_id          BIGINT       NOT NULL,
    fecha_desde        DATE         NOT NULL,
    fecha_hasta        DATE         NOT NULL,
    tipo               VARCHAR(10)  NOT NULL,
    motivo             VARCHAR(500) NOT NULL,
    ruta_archivo       VARCHAR(400),                       -- MinIO
    estado             VARCHAR(10)  NOT NULL DEFAULT 'PENDIENTE',
    solicitado_por     BIGINT       NOT NULL,              -- usuario_id (apoderado)
    resuelto_por       BIGINT,
    resuelto_en        TIMESTAMP,
    comentario_resolucion VARCHAR(300),
    creado_en          TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_just_fechas CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_just_tipo CHECK (tipo IN ('MEDICA','FAMILIAR','OTRO')),
    CONSTRAINT ck_just_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA'))
);
CREATE INDEX idx_just_pend ON justificaciones (estado, creado_en) WHERE estado = 'PENDIENTE';
CREATE INDEX idx_just_alumno ON justificaciones (alumno_id, fecha_desde);

-- Auditoría: cambios hechos sobre una asistencia ya registrada
CREATE TABLE asistencia_auditoria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle_id      BIGINT      NOT NULL,
    estado_anterior VARCHAR(11),
    estado_nuevo    VARCHAR(11) NOT NULL,
    motivo          VARCHAR(300),
    usuario_id      BIGINT,
    cambiado_en     TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_aud_detalle ON asistencia_auditoria (detalle_id);

-- Idempotencia de consumidores Kafka (entrega al menos una vez)
CREATE TABLE eventos_procesados (
    event_id      UUID        PRIMARY KEY,
    event_type    VARCHAR(80) NOT NULL,
    procesado_en  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_eventos_proc_fecha ON eventos_procesados (procesado_en);


-- Tabla de ShedLock: evita que varias réplicas ejecuten el mismo @Scheduled
CREATE TABLE shedlock (
    name       VARCHAR(64)  PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);


-- =====================================================================
-- matricula_db | matricula-ms | EduSpace
-- Vincula alumno + año + grado + sección. Controla cupos de forma atómica
-- y orquesta (por eventos) el pago de la matrícula.
-- Ids de otros servicios (alumno, año, grado, sección, usuario) = columnas
-- simples, sin FK. alumno_nombre es una copia (snapshot) para listados.
-- =====================================================================
CREATE TABLE campanias_matricula (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id      BIGINT       NOT NULL,                    -- planificacion-ms
    nombre       VARCHAR(80)  NOT NULL,
    fecha_inicio DATE         NOT NULL,
    fecha_fin    DATE         NOT NULL,
    estado       VARCHAR(12)  NOT NULL DEFAULT 'PLANIFICADA',
    creado_en    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_campania UNIQUE (anio_id, nombre),
    CONSTRAINT ck_campania_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_campania_estado CHECK (estado IN ('PLANIFICADA','ABIERTA','CERRADA'))
);

-- Cupos por sección. "ocupados" se actualiza con un UPDATE condicional
-- (ocupados < capacidad) para que dos matrículas simultáneas no pasen el límite.
CREATE TABLE cupos_seccion (
    seccion_id     BIGINT      PRIMARY KEY,                -- planificacion-ms
    anio_id        BIGINT      NOT NULL,
    nivel_id       BIGINT,
    grado_id       BIGINT      NOT NULL,
    seccion_nombre VARCHAR(10) NOT NULL,
    capacidad      SMALLINT    NOT NULL,
    ocupados       SMALLINT    NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_cupos_rango CHECK (ocupados >= 0 AND ocupados <= capacidad),
    CONSTRAINT ck_cupos_capacidad CHECK (capacidad > 0)
);
CREATE INDEX idx_cupos_anio_grado ON cupos_seccion (anio_id, grado_id);

CREATE TABLE matriculas (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(25)  NOT NULL,
    alumno_id             BIGINT       NOT NULL,           -- alumnos-ms
    alumno_nombre         VARCHAR(220) NOT NULL,
    anio_id               BIGINT       NOT NULL,           -- planificacion-ms
    nivel_id              BIGINT,
    grado_id              BIGINT       NOT NULL,
    seccion_id            BIGINT       NOT NULL REFERENCES cupos_seccion(seccion_id),
    campania_id           BIGINT       REFERENCES campanias_matricula(id),
    tipo                  VARCHAR(15)  NOT NULL DEFAULT 'NUEVA',
    estado                VARCHAR(15)  NOT NULL DEFAULT 'PRE_MATRICULA',
    matricula_anterior_id BIGINT       REFERENCES matriculas(id),
    vence_en              TIMESTAMP,                       -- si sigue PRE_MATRICULA y vence -> se anula
    observaciones         VARCHAR(500),
    creado_por            BIGINT,                          -- usuario_id (auth-ms)
    creado_en             TIMESTAMP    NOT NULL DEFAULT now(),
    confirmada_en         TIMESTAMP,
    cerrada_en            TIMESTAMP,
    motivo_cierre         VARCHAR(300),
    actualizado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0, -- bloqueo optimista
    CONSTRAINT uk_matricula_codigo UNIQUE (codigo),
    CONSTRAINT ck_matricula_tipo CHECK (tipo IN ('NUEVA','RATIFICACION','REINGRESO')),
    CONSTRAINT ck_matricula_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
-- Un alumno solo puede tener UNA matrícula viva por año
CREATE UNIQUE INDEX uk_matricula_viva ON matriculas (alumno_id, anio_id)
    WHERE estado IN ('PRE_MATRICULA','MATRICULADO');
CREATE INDEX idx_matriculas_seccion ON matriculas (seccion_id, estado);
CREATE INDEX idx_matriculas_anio_estado ON matriculas (anio_id, estado);
CREATE INDEX idx_matriculas_alumno ON matriculas (alumno_id);
CREATE INDEX idx_matriculas_vencen ON matriculas (vence_en) WHERE estado = 'PRE_MATRICULA';

CREATE TABLE matricula_requisitos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id  BIGINT       NOT NULL REFERENCES matriculas(id) ON DELETE CASCADE,
    tipo          VARCHAR(30)  NOT NULL,
    cumplido      BOOLEAN      NOT NULL DEFAULT FALSE,
    observacion   VARCHAR(300),
    verificado_por BIGINT,
    verificado_en TIMESTAMP,
    CONSTRAINT uk_requisito UNIQUE (matricula_id, tipo),
    CONSTRAINT ck_requisito_tipo CHECK (tipo IN ('FICHA_FIRMADA','CONSTANCIA_NO_ADEUDO','CERTIFICADO_ESTUDIOS','EXPEDIENTE_COMPLETO'))
);

CREATE TABLE matricula_historial (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id      BIGINT       NOT NULL REFERENCES matriculas(id) ON DELETE CASCADE,
    tipo_cambio       VARCHAR(20)  NOT NULL,
    estado_anterior   VARCHAR(15),
    estado_nuevo      VARCHAR(15),
    seccion_anterior_id BIGINT,
    seccion_nueva_id  BIGINT,
    motivo            VARCHAR(300),
    usuario_id        BIGINT,
    fecha             TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_hist_tipo CHECK (tipo_cambio IN ('CREACION','CONFIRMACION','TRASLADO_SECCION','RETIRO','ANULACION'))
);
CREATE INDEX idx_mat_hist ON matricula_historial (matricula_id, fecha DESC);

-- Outbox transaccional: el evento se guarda en la MISMA transacción del cambio
-- y un publicador lo envía a Kafka (FOR UPDATE SKIP LOCKED). No se pierde ni
-- si el servicio cae entre el commit y el envío.
CREATE TABLE outbox_eventos (
    id             UUID         PRIMARY KEY,               -- = eventId del sobre
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    topic          VARCHAR(80)  NOT NULL,
    clave          VARCHAR(80)  NOT NULL,
    payload        JSONB        NOT NULL,
    creado_en      TIMESTAMP    NOT NULL DEFAULT now(),
    enviado_en     TIMESTAMP,
    intentos       SMALLINT     NOT NULL DEFAULT 0,
    ultimo_error   VARCHAR(500)
);
CREATE INDEX idx_outbox_pendientes ON outbox_eventos (creado_en) WHERE enviado_en IS NULL;


-- Idempotencia de consumidores Kafka (entrega al menos una vez)
CREATE TABLE eventos_procesados (
    event_id      UUID        PRIMARY KEY,
    event_type    VARCHAR(80) NOT NULL,
    procesado_en  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_eventos_proc_fecha ON eventos_procesados (procesado_en);


-- Tabla de ShedLock: evita que varias réplicas ejecuten el mismo @Scheduled
CREATE TABLE shedlock (
    name       VARCHAR(64)  PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);


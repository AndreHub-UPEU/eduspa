-- Réplica local (read model) de matrículas, alimentada por eventos matricula.*
CREATE TABLE matriculas_local (
    matricula_id   BIGINT       PRIMARY KEY,
    alumno_id      BIGINT       NOT NULL,
    alumno_nombre  VARCHAR(220) NOT NULL,
    anio_id        BIGINT       NOT NULL,
    nivel_id       BIGINT,
    grado_id       BIGINT       NOT NULL,
    seccion_id     BIGINT       NOT NULL,
    estado         VARCHAR(15)  NOT NULL,
    actualizado_en TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ml_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
CREATE INDEX idx_ml_seccion ON matriculas_local (seccion_id, estado);
CREATE INDEX idx_ml_alumno ON matriculas_local (alumno_id);


CREATE TABLE tareas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id           BIGINT       NOT NULL,
    periodo_id        BIGINT       NOT NULL,
    seccion_id        BIGINT       NOT NULL,
    curso_id          BIGINT       NOT NULL,
    docente_id        BIGINT       NOT NULL,               -- planificacion-ms
    titulo            VARCHAR(200) NOT NULL,
    descripcion       TEXT,
    publicada_en      TIMESTAMP,
    fecha_entrega     TIMESTAMP    NOT NULL,
    permite_tardia    BOOLEAN      NOT NULL DEFAULT FALSE,
    puntaje_maximo    NUMERIC(5,2) NOT NULL DEFAULT 20,
    estado            VARCHAR(10)  NOT NULL DEFAULT 'BORRADOR',
    creada_en         TIMESTAMP    NOT NULL DEFAULT now(),
    actualizada_en    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_tarea_estado CHECK (estado IN ('BORRADOR','PUBLICADA','CERRADA')),
    CONSTRAINT ck_tarea_puntaje CHECK (puntaje_maximo > 0)
);
CREATE INDEX idx_tareas_seccion ON tareas (seccion_id, estado, fecha_entrega);
CREATE INDEX idx_tareas_docente ON tareas (docente_id, estado);
CREATE INDEX idx_tareas_curso_periodo ON tareas (curso_id, periodo_id);

CREATE TABLE tarea_adjuntos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id       BIGINT       NOT NULL REFERENCES tareas(id) ON DELETE CASCADE,
    nombre_archivo VARCHAR(200) NOT NULL,
    ruta_storage   VARCHAR(400) NOT NULL,
    content_type   VARCHAR(100),
    tamano_bytes   BIGINT
);
CREATE INDEX idx_tarea_adj ON tarea_adjuntos (tarea_id);

CREATE TABLE entregas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id         BIGINT       NOT NULL REFERENCES tareas(id) ON DELETE CASCADE,
    matricula_id     BIGINT       NOT NULL,
    alumno_id        BIGINT       NOT NULL,
    comentario       VARCHAR(1000),
    entregada_en     TIMESTAMP    NOT NULL DEFAULT now(),
    es_tardia        BOOLEAN      NOT NULL DEFAULT FALSE,
    version          SMALLINT     NOT NULL DEFAULT 1,      -- reenvíos permitidos antes de calificar
    estado           VARCHAR(10)  NOT NULL DEFAULT 'ENTREGADA',
    nota             NUMERIC(5,2),
    retroalimentacion TEXT,
    calificada_en    TIMESTAMP,
    calificada_por   BIGINT,
    CONSTRAINT uk_entrega UNIQUE (tarea_id, matricula_id),
    CONSTRAINT ck_entrega_estado CHECK (estado IN ('ENTREGADA','CALIFICADA','DEVUELTA')),
    CONSTRAINT ck_entrega_nota CHECK (nota IS NULL OR nota >= 0)
);
CREATE INDEX idx_entregas_alumno ON entregas (alumno_id);
CREATE INDEX idx_entregas_pend ON entregas (tarea_id) WHERE estado = 'ENTREGADA';

CREATE TABLE entrega_archivos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrega_id     BIGINT       NOT NULL REFERENCES entregas(id) ON DELETE CASCADE,
    nombre_archivo VARCHAR(200) NOT NULL,
    ruta_storage   VARCHAR(400) NOT NULL,
    content_type   VARCHAR(100),
    tamano_bytes   BIGINT,
    subido_en      TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_entrega_arch ON entrega_archivos (entrega_id);

-- Idempotencia de consumidores Kafka (entrega al menos una vez)
CREATE TABLE eventos_procesados (
    event_id      UUID        PRIMARY KEY,
    event_type    VARCHAR(80) NOT NULL,
    procesado_en  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_eventos_proc_fecha ON eventos_procesados (procesado_en);


-- Tabla de ShedLock: evita que varias réplicas ejecuten el mismo @Scheduled
CREATE TABLE shedlock (
    name       VARCHAR(64)  PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);


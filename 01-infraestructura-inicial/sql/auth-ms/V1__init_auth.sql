-- auth_db | auth-ms | EduSpace
-- Usuarios, roles y refresh tokens. Roles SIN prefijo ROLE_ (el prefijo
-- se agrega al convertir el JWT en autoridades de Spring).
-- Vínculo con personas: NO se guarda aquí. alumnos-ms / planificacion-ms
-- guardan usuario_id de este servicio (sin FK entre bases).
-- =====================================================================
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(30)  NOT NULL,
    descripcion VARCHAR(150),
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

CREATE TABLE usuarios (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(80)  NOT NULL,
    email               VARCHAR(150) NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,            -- BCrypt
    nombres             VARCHAR(100) NOT NULL,
    apellidos           VARCHAR(100) NOT NULL,
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos   SMALLINT     NOT NULL DEFAULT 0,
    bloqueado_hasta     TIMESTAMP,
    debe_cambiar_clave  BOOLEAN      NOT NULL DEFAULT FALSE,
    ultimo_login        TIMESTAMP,
    creado_en           TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_intentos CHECK (intentos_fallidos >= 0)
);

CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    rol_id     BIGINT NOT NULL REFERENCES roles(id),
    PRIMARY KEY (usuario_id, rol_id)
);
CREATE INDEX idx_usuario_roles_rol ON usuario_roles (rol_id);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash  VARCHAR(100) NOT NULL,                    -- se guarda el hash, nunca el token
    expira_en   TIMESTAMP   NOT NULL,
    revocado    BOOLEAN     NOT NULL DEFAULT FALSE,
    creado_en   TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_refresh_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_usuario ON refresh_tokens (usuario_id) WHERE NOT revocado;


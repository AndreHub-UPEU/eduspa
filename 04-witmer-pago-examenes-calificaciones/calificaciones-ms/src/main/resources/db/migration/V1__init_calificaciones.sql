-- Réplica local (read model) de matrículas, alimentada por eventos matricula.*
CREATE TABLE matriculas_local (
    matricula_id   BIGINT       PRIMARY KEY,
    alumno_id      BIGINT       NOT NULL,
    alumno_nombre  VARCHAR(220) NOT NULL,
    anio_id        BIGINT       NOT NULL,
    nivel_id       BIGINT,
    grado_id       BIGINT       NOT NULL,
    seccion_id     BIGINT       NOT NULL,
    estado         VARCHAR(15)  NOT NULL,
    actualizado_en TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ml_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
CREATE INDEX idx_ml_seccion ON matriculas_local (seccion_id, estado);
CREATE INDEX idx_ml_alumno ON matriculas_local (alumno_id);


CREATE TABLE parametros_evaluacion (
    clave   VARCHAR(40)  PRIMARY KEY,
    valor   VARCHAR(40)  NOT NULL,
    detalle VARCHAR(200)
);

CREATE TABLE escalas_literales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel_codigo VARCHAR(15) NOT NULL,                     -- 'PRIMARIA', 'INICIAL'...
    literal     VARCHAR(5)   NOT NULL,
    nota_min    NUMERIC(5,2) NOT NULL,
    nota_max    NUMERIC(5,2) NOT NULL,
    descripcion VARCHAR(100),
    CONSTRAINT uk_escala UNIQUE (nivel_codigo, literal),
    CONSTRAINT ck_escala_rango CHECK (nota_max >= nota_min)
);

CREATE TABLE criterios_evaluacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id     BIGINT       NOT NULL,
    periodo_id  BIGINT       NOT NULL,
    seccion_id  BIGINT       NOT NULL,
    curso_id    BIGINT       NOT NULL,
    nombre      VARCHAR(80)  NOT NULL,
    peso        NUMERIC(5,2) NOT NULL,                     -- porcentaje; la suma por curso debe ser 100 (se valida al cerrar)
    origen_tipo VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',
    creado_por  BIGINT,
    creado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_criterio UNIQUE (periodo_id, seccion_id, curso_id, nombre),
    CONSTRAINT ck_criterio_peso CHECK (peso > 0 AND peso <= 100),
    CONSTRAINT ck_criterio_origen CHECK (origen_tipo IN ('MANUAL','TAREAS','EXAMENES'))
);
CREATE INDEX idx_criterios_curso ON criterios_evaluacion (periodo_id, seccion_id, curso_id);

CREATE TABLE notas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id  BIGINT       NOT NULL,
    alumno_id     BIGINT       NOT NULL,
    seccion_id    BIGINT       NOT NULL,
    curso_id      BIGINT       NOT NULL,
    periodo_id    BIGINT       NOT NULL,
    criterio_id   BIGINT       NOT NULL REFERENCES criterios_evaluacion(id),
    valor         NUMERIC(5,2) NOT NULL,
    origen        VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',
    origen_id     BIGINT,                                  -- id de tarea o examen en el servicio origen
    registrado_por BIGINT,
    registrado_en TIMESTAMP    NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_nota_valor CHECK (valor >= 0 AND valor <= 20),
    CONSTRAINT ck_nota_origen CHECK (origen IN ('MANUAL','TAREA','EXAMEN'))
);
-- Evita duplicar la nota de la misma tarea/examen si el evento se repite
CREATE UNIQUE INDEX uk_nota_origen ON notas (matricula_id, criterio_id, origen, COALESCE(origen_id, 0));
CREATE INDEX idx_notas_curso ON notas (periodo_id, seccion_id, curso_id);
CREATE INDEX idx_notas_alumno ON notas (alumno_id, periodo_id);

CREATE TABLE promedios_periodo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id  BIGINT       NOT NULL,
    alumno_id     BIGINT       NOT NULL,
    seccion_id    BIGINT       NOT NULL,
    curso_id      BIGINT       NOT NULL,
    periodo_id    BIGINT       NOT NULL,
    promedio      NUMERIC(5,2) NOT NULL,
    literal       VARCHAR(5),
    estado        VARCHAR(10)  NOT NULL DEFAULT 'BORRADOR',
    calculado_en  TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_promedio UNIQUE (matricula_id, curso_id, periodo_id),
    CONSTRAINT ck_prom_estado CHECK (estado IN ('BORRADOR','CERRADO'))
);
CREATE INDEX idx_prom_seccion ON promedios_periodo (periodo_id, seccion_id, curso_id);

CREATE TABLE cierres_periodo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id      BIGINT      NOT NULL,
    periodo_id      BIGINT      NOT NULL,
    estado          VARCHAR(10) NOT NULL DEFAULT 'ABIERTO',
    cerrado_por     BIGINT,
    cerrado_en      TIMESTAMP,
    reabierto_por   BIGINT,
    reabierto_en    TIMESTAMP,
    motivo_reapertura VARCHAR(300),
    CONSTRAINT uk_cierre UNIQUE (seccion_id, periodo_id),
    CONSTRAINT ck_cierre_estado CHECK (estado IN ('ABIERTO','CERRADO','REABIERTO'))
);

CREATE TABLE boletines (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id  BIGINT       NOT NULL,
    alumno_id     BIGINT       NOT NULL,
    periodo_id    BIGINT,                                  -- NULL = boletín anual
    version       INTEGER      NOT NULL DEFAULT 1,
    estado        VARCHAR(8)   NOT NULL DEFAULT 'VIGENTE',
    ruta_pdf      VARCHAR(400) NOT NULL,                   -- MinIO bucket 'boletines'
    generado_por  BIGINT,
    generado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_bol_estado CHECK (estado IN ('VIGENTE','ANULADO'))
);
CREATE UNIQUE INDEX uk_boletin_version ON boletines (matricula_id, COALESCE(periodo_id, 0), version);
CREATE INDEX idx_boletines_alumno ON boletines (alumno_id);

CREATE TABLE resultados_anuales (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id   BIGINT       NOT NULL,
    alumno_id      BIGINT       NOT NULL,
    anio_id        BIGINT       NOT NULL,
    curso_id       BIGINT       NOT NULL,
    promedio_final NUMERIC(5,2) NOT NULL,
    literal        VARCHAR(5),
    estado         VARCHAR(14)  NOT NULL,
    calculado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_resultado UNIQUE (matricula_id, curso_id),
    CONSTRAINT ck_res_estado CHECK (estado IN ('APROBADO','DESAPROBADO','RECUPERACION'))
);
CREATE INDEX idx_res_alumno_anio ON resultados_anuales (alumno_id, anio_id);


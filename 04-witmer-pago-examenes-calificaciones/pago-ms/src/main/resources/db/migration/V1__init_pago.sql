-- Réplica local de matrículas (alimentada por matricula.*) + responsable de pago
CREATE TABLE matriculas_local (
    matricula_id        BIGINT       PRIMARY KEY,
    alumno_id           BIGINT       NOT NULL,
    alumno_nombre       VARCHAR(220) NOT NULL,
    anio_id             BIGINT       NOT NULL,
    nivel_id            BIGINT,
    grado_id            BIGINT       NOT NULL,
    seccion_id          BIGINT       NOT NULL,
    estado              VARCHAR(15)  NOT NULL,
    responsable_usuario_id BIGINT,                         -- apoderado responsable de pago (alumnos-ms)
    responsable_nombre  VARCHAR(220),
    actualizado_en      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_pml_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
CREATE INDEX idx_pml_alumno ON matriculas_local (alumno_id);
CREATE INDEX idx_pml_seccion ON matriculas_local (seccion_id);

CREATE TABLE conceptos_pago (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(30)  NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    tipo    VARCHAR(10)  NOT NULL,
    activo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_concepto_codigo UNIQUE (codigo),
    CONSTRAINT ck_concepto_tipo CHECK (tipo IN ('MATRICULA','PENSION','OTRO'))
);

CREATE TABLE tarifas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id          BIGINT        NOT NULL,
    nivel_id         BIGINT        NOT NULL,
    grado_id         BIGINT,                               -- NULL = aplica a todo el nivel
    concepto_id      BIGINT        NOT NULL REFERENCES conceptos_pago(id),
    monto            NUMERIC(10,2) NOT NULL,
    num_cuotas       SMALLINT      NOT NULL DEFAULT 1,
    mes_inicio       SMALLINT      NOT NULL DEFAULT 3,     -- marzo
    dia_vencimiento  SMALLINT      NOT NULL DEFAULT 5,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_tarifa_monto CHECK (monto >= 0),
    CONSTRAINT ck_tarifa_cuotas CHECK (num_cuotas BETWEEN 1 AND 12),
    CONSTRAINT ck_tarifa_mes CHECK (mes_inicio BETWEEN 1 AND 12),
    CONSTRAINT ck_tarifa_dia CHECK (dia_vencimiento BETWEEN 1 AND 28)
);
CREATE UNIQUE INDEX uk_tarifa ON tarifas (anio_id, nivel_id, COALESCE(grado_id, 0), concepto_id);

CREATE TABLE descuentos (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100)  NOT NULL,
    tipo      VARCHAR(10)   NOT NULL,
    valor     NUMERIC(10,2) NOT NULL,
    aplica_a  VARCHAR(10)   NOT NULL DEFAULT 'PENSION',
    activo    BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_desc_tipo CHECK (tipo IN ('PORCENTAJE','MONTO_FIJO')),
    CONSTRAINT ck_desc_valor CHECK (valor > 0 AND (tipo <> 'PORCENTAJE' OR valor <= 100)),
    CONSTRAINT ck_desc_aplica CHECK (aplica_a IN ('MATRICULA','PENSION','TODO'))
);

CREATE TABLE descuentos_alumno (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id     BIGINT       NOT NULL,
    descuento_id  BIGINT       NOT NULL REFERENCES descuentos(id),
    anio_id       BIGINT       NOT NULL,
    motivo        VARCHAR(300),
    aprobado_por  BIGINT,
    vigente       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_desc_alumno UNIQUE (alumno_id, descuento_id, anio_id)
);

CREATE TABLE cuotas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id      BIGINT        NOT NULL REFERENCES matriculas_local(matricula_id),
    alumno_id         BIGINT        NOT NULL,
    anio_id           BIGINT        NOT NULL,
    concepto_id       BIGINT        NOT NULL REFERENCES conceptos_pago(id),
    tarifa_id         BIGINT        REFERENCES tarifas(id),
    descripcion       VARCHAR(150)  NOT NULL,
    numero_cuota      SMALLINT      NOT NULL DEFAULT 1,
    monto_base        NUMERIC(10,2) NOT NULL,
    descuento         NUMERIC(10,2) NOT NULL DEFAULT 0,
    mora              NUMERIC(10,2) NOT NULL DEFAULT 0,
    monto_total       NUMERIC(10,2) NOT NULL,
    saldo             NUMERIC(10,2) NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    estado            VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    aviso_enviado     BOOLEAN       NOT NULL DEFAULT FALSE,
    creada_en         TIMESTAMP     NOT NULL DEFAULT now(),
    actualizada_en    TIMESTAMP     NOT NULL DEFAULT now(),
    version           BIGINT        NOT NULL DEFAULT 0,    -- bloqueo optimista: dos cajeros no cobran la misma cuota
    -- Si el evento matricula.creada se repite, no se duplican cuotas
    CONSTRAINT uk_cuota UNIQUE (matricula_id, concepto_id, numero_cuota),
    CONSTRAINT ck_cuota_montos CHECK (monto_base >= 0 AND descuento >= 0 AND mora >= 0 AND monto_total >= 0),
    CONSTRAINT ck_cuota_saldo CHECK (saldo >= 0 AND saldo <= monto_total),
    CONSTRAINT ck_cuota_estado CHECK (estado IN ('PENDIENTE','PARCIAL','PAGADA','VENCIDA','ANULADA'))
);
CREATE INDEX idx_cuotas_alumno ON cuotas (alumno_id, estado);
CREATE INDEX idx_cuotas_venc ON cuotas (fecha_vencimiento) WHERE estado IN ('PENDIENTE','PARCIAL','VENCIDA');
CREATE INDEX idx_cuotas_matricula ON cuotas (matricula_id);

CREATE TABLE cajas_sesion (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cajero_usuario_id       BIGINT        NOT NULL,
    apertura_en             TIMESTAMP     NOT NULL DEFAULT now(),
    monto_apertura          NUMERIC(10,2) NOT NULL DEFAULT 0,
    cierre_en               TIMESTAMP,
    monto_cierre_declarado  NUMERIC(10,2),
    monto_cierre_sistema    NUMERIC(10,2),
    diferencia              NUMERIC(10,2),
    estado                  VARCHAR(8)    NOT NULL DEFAULT 'ABIERTA',
    CONSTRAINT ck_caja_estado CHECK (estado IN ('ABIERTA','CERRADA'))
);
-- Un cajero solo puede tener una caja abierta
CREATE UNIQUE INDEX uk_caja_abierta ON cajas_sesion (cajero_usuario_id) WHERE estado = 'ABIERTA';

CREATE TABLE series_comprobante (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           VARCHAR(10) NOT NULL,
    serie          VARCHAR(4)  NOT NULL,
    ultimo_numero  BIGINT      NOT NULL DEFAULT 0,         -- se incrementa con SELECT ... FOR UPDATE
    activa         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_serie UNIQUE (tipo, serie),
    CONSTRAINT ck_serie_tipo CHECK (tipo IN ('RECIBO','BOLETA'))
);

CREATE TABLE pagos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id         BIGINT        NOT NULL,
    pagador_nombre    VARCHAR(200),
    pagador_documento VARCHAR(20),
    monto_total       NUMERIC(10,2) NOT NULL,
    medio             VARCHAR(15)   NOT NULL,
    referencia        VARCHAR(80),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'CONFIRMADO',
    caja_sesion_id    BIGINT        REFERENCES cajas_sesion(id),
    registrado_por    BIGINT,                              -- usuario_id (cajero o apoderado)
    pagado_en         TIMESTAMP     NOT NULL DEFAULT now(),
    anulado_en        TIMESTAMP,
    anulado_por       BIGINT,
    motivo_anulacion  VARCHAR(300),
    idempotency_key   VARCHAR(80),                         -- evita cobrar dos veces por doble clic / reintento
    CONSTRAINT ck_pago_monto CHECK (monto_total > 0),
    CONSTRAINT ck_pago_medio CHECK (medio IN ('EFECTIVO','TARJETA','YAPE_PLIN','TRANSFERENCIA','ONLINE_SIMULADO')),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('CONFIRMADO','ANULADO'))
);
CREATE UNIQUE INDEX uk_pago_idem ON pagos (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX idx_pagos_alumno ON pagos (alumno_id, pagado_en DESC);
CREATE INDEX idx_pagos_caja ON pagos (caja_sesion_id);

CREATE TABLE pago_detalle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id        BIGINT        NOT NULL REFERENCES pagos(id) ON DELETE CASCADE,
    cuota_id       BIGINT        NOT NULL REFERENCES cuotas(id),
    monto_aplicado NUMERIC(10,2) NOT NULL,
    CONSTRAINT uk_pago_cuota UNIQUE (pago_id, cuota_id),
    CONSTRAINT ck_detalle_monto CHECK (monto_aplicado > 0)
);
CREATE INDEX idx_pago_detalle_cuota ON pago_detalle (cuota_id);

CREATE TABLE comprobantes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id     BIGINT        NOT NULL REFERENCES pagos(id),
    tipo        VARCHAR(10)   NOT NULL,
    serie       VARCHAR(4)    NOT NULL,
    numero      BIGINT        NOT NULL,
    total       NUMERIC(10,2) NOT NULL,
    estado      VARCHAR(8)    NOT NULL DEFAULT 'EMITIDO',
    ruta_pdf    VARCHAR(400),
    emitido_en  TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uk_comprobante_pago UNIQUE (pago_id),
    CONSTRAINT uk_comprobante_numero UNIQUE (tipo, serie, numero),
    CONSTRAINT ck_comp_estado CHECK (estado IN ('EMITIDO','ANULADO'))
);


-- =====================================================================
-- examenes_db | examenes-ms | EduSpace
-- Banco de preguntas, exámenes, intentos y respuestas. El tiempo límite
-- lo controla el SERVIDOR (vence_en), no el reloj del cliente.
-- =====================================================================

-- Réplica local (read model) de matrículas, alimentada por eventos matricula.*
CREATE TABLE matriculas_local (
    matricula_id   BIGINT       PRIMARY KEY,
    alumno_id      BIGINT       NOT NULL,
    alumno_nombre  VARCHAR(220) NOT NULL,
    anio_id        BIGINT       NOT NULL,
    nivel_id       BIGINT,
    grado_id       BIGINT       NOT NULL,
    seccion_id     BIGINT       NOT NULL,
    estado         VARCHAR(15)  NOT NULL,
    actualizado_en TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ml_estado CHECK (estado IN ('PRE_MATRICULA','MATRICULADO','RETIRADO','ANULADO','TRASLADADO'))
);
CREATE INDEX idx_ml_seccion ON matriculas_local (seccion_id, estado);
CREATE INDEX idx_ml_alumno ON matriculas_local (alumno_id);


CREATE TABLE preguntas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id    BIGINT       NOT NULL,
    docente_id  BIGINT       NOT NULL,
    tema        VARCHAR(100),
    tipo        VARCHAR(12)  NOT NULL,
    enunciado   TEXT         NOT NULL,
    puntaje     NUMERIC(5,2) NOT NULL DEFAULT 1,
    activa      BOOLEAN      NOT NULL DEFAULT TRUE,
    creada_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_preg_tipo CHECK (tipo IN ('OPCION_UNICA','OPCION_MULTIPLE','VERDADERO_FALSO','ABIERTA')),
    CONSTRAINT ck_preg_puntaje CHECK (puntaje > 0)
);
CREATE INDEX idx_preg_curso ON preguntas (curso_id, activa);
CREATE INDEX idx_preg_docente ON preguntas (docente_id);

CREATE TABLE opciones_pregunta (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id  BIGINT       NOT NULL REFERENCES preguntas(id) ON DELETE CASCADE,
    texto        VARCHAR(500) NOT NULL,
    es_correcta  BOOLEAN      NOT NULL DEFAULT FALSE,
    orden        SMALLINT     NOT NULL DEFAULT 1,
    CONSTRAINT uk_opcion_orden UNIQUE (pregunta_id, orden)
);

CREATE TABLE examenes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id          BIGINT       NOT NULL,
    periodo_id       BIGINT       NOT NULL,
    seccion_id       BIGINT       NOT NULL,
    curso_id         BIGINT       NOT NULL,
    docente_id       BIGINT       NOT NULL,
    titulo           VARCHAR(200) NOT NULL,
    instrucciones    TEXT,
    fecha_inicio     TIMESTAMP    NOT NULL,
    fecha_fin        TIMESTAMP    NOT NULL,
    duracion_min     SMALLINT     NOT NULL,
    intentos_max     SMALLINT     NOT NULL DEFAULT 1,
    barajar_preguntas BOOLEAN     NOT NULL DEFAULT FALSE,
    puntaje_total    NUMERIC(6,2) NOT NULL DEFAULT 0,      -- se recalcula al publicar
    estado           VARCHAR(10)  NOT NULL DEFAULT 'BORRADOR',
    creado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    publicado_en     TIMESTAMP,
    CONSTRAINT ck_exam_ventana CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT ck_exam_duracion CHECK (duracion_min > 0),
    CONSTRAINT ck_exam_intentos CHECK (intentos_max >= 1),
    CONSTRAINT ck_exam_estado CHECK (estado IN ('BORRADOR','PUBLICADO','CERRADO','CALIFICADO'))
);
CREATE INDEX idx_exam_seccion ON examenes (seccion_id, estado, fecha_inicio);
CREATE INDEX idx_exam_docente ON examenes (docente_id, estado);

CREATE TABLE examen_preguntas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id    BIGINT       NOT NULL REFERENCES examenes(id) ON DELETE CASCADE,
    pregunta_id  BIGINT       NOT NULL REFERENCES preguntas(id),
    orden        SMALLINT     NOT NULL,
    puntaje      NUMERIC(5,2) NOT NULL,
    CONSTRAINT uk_exam_preg UNIQUE (examen_id, pregunta_id),
    CONSTRAINT uk_exam_orden UNIQUE (examen_id, orden),
    CONSTRAINT ck_ep_puntaje CHECK (puntaje > 0)
);

CREATE TABLE intentos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id        BIGINT       NOT NULL REFERENCES examenes(id),
    matricula_id     BIGINT       NOT NULL,
    alumno_id        BIGINT       NOT NULL,
    numero           SMALLINT     NOT NULL DEFAULT 1,
    iniciado_en      TIMESTAMP    NOT NULL DEFAULT now(),
    vence_en         TIMESTAMP    NOT NULL,                -- min(iniciado+duración, fecha_fin del examen)
    enviado_en       TIMESTAMP,
    estado           VARCHAR(12)  NOT NULL DEFAULT 'EN_CURSO',
    puntaje_obtenido NUMERIC(6,2),
    nota             NUMERIC(5,2),
    calificado_en    TIMESTAMP,
    CONSTRAINT uk_intento UNIQUE (examen_id, matricula_id, numero),
    CONSTRAINT ck_int_estado CHECK (estado IN ('EN_CURSO','ENVIADO','CALIFICADO','VENCIDO'))
);
CREATE INDEX idx_int_examen ON intentos (examen_id, estado);
CREATE INDEX idx_int_alumno ON intentos (alumno_id);
CREATE INDEX idx_int_vencen ON intentos (vence_en) WHERE estado = 'EN_CURSO';

CREATE TABLE respuestas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intento_id        BIGINT       NOT NULL REFERENCES intentos(id) ON DELETE CASCADE,
    pregunta_id       BIGINT       NOT NULL REFERENCES preguntas(id),
    opciones_ids      BIGINT[],                            -- opción(es) marcadas
    texto_respuesta   TEXT,
    puntaje_obtenido  NUMERIC(5,2),
    requiere_revision BOOLEAN      NOT NULL DEFAULT FALSE,  -- preguntas ABIERTAS
    revisada_por      BIGINT,
    guardada_en       TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_respuesta UNIQUE (intento_id, pregunta_id)  -- guardado incremental = UPSERT
);

-- Idempotencia de consumidores Kafka (entrega al menos una vez)
CREATE TABLE eventos_procesados (
    event_id      UUID        PRIMARY KEY,
    event_type    VARCHAR(80) NOT NULL,
    procesado_en  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX idx_eventos_proc_fecha ON eventos_procesados (procesado_en);


-- Tabla de ShedLock: evita que varias réplicas ejecuten el mismo @Scheduled
CREATE TABLE shedlock (
    name       VARCHAR(64)  PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);

